export function isValidClearance(raw: string): boolean {
  const v = raw.trim().toLowerCase();
  return (
    v === "4" ||
    v === "5" ||
    v === "4/7843" ||
    v === "5/7843" ||
    v === "keter" ||
    v === "уровень 4" ||
    v === "level 4" ||
    v === "lvl 4" ||
    v === "4/keter"
  );
}
